-- V22 窗口结算失败时的现金：不再自动视为“已撤回”
--
-- 现金已收、结算未完成时，现金是否已当面退还患者，系统无从得知。此前撤回流程把现金直接记为“已撤回”，
-- 收费单随即可以重新收费；若现金实际没有退还，患者会被重复收费。
-- 现在这类现金记为 6（现金待确认退还），整次结算转为收款异常，财务逐笔核实后才能解除锁定。
-- 只修改列注释，不改动已有数据。
-- =====================================================================

ALTER TABLE counter_checkout_tender
    MODIFY COLUMN status TINYINT NOT NULL
        COMMENT '0收取中 1已收 2已撤回 3撤回失败 4已核实退还 5已核实未扣款 6现金待确认退还';
